class ReplyService:
    def __init__(self, api_key: str, model: str, persona: str = DEFAULT_PERSONA):
        self.client = build_client(api_key)
        self.model = model
        self.persona = persona

    def generate(self, history_messages: list[dict]) -> str:
        messages = [{"role": "system", "content": self.persona}] + history_messages
        try:
            rsp = self.client.chat.completions.create(
                model=self.model,
                messages=messages,
                temperature=0.7,
                top_p=0.9,
                max_tokens=250,
            )
            return rsp.choices[0].message.content
        except Exception as e:
            # fallback امن
            return "اوه الان حالم خوب نیست یه لحظه بهم فرصت بده 😊"
